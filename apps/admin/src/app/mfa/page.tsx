import { redirect } from 'next/navigation';
import { signOut } from '@/app/actions';
import { AuthCard } from '@/components/AuthCard';
import { Flash } from '@/components/Flash';
import { requireUser } from '@/lib/dal';
import type { SearchParams } from '@/lib/flash';
import { t } from '@/lib/i18n';
import { TotpForm } from './TotpForm';

export const dynamic = 'force-dynamic';

export default async function MfaPage({ searchParams }: { searchParams: SearchParams }) {
  const params = await searchParams;
  const { supabase, aal } = await requireUser();
  if (aal === 'aal2') redirect('/');
  const { data: factors } = await supabase.auth.mfa.listFactors();
  const verified = factors?.totp.find((f) => f.status === 'verified');

  let factorId: string;
  let enrolment: { qr: string; secret: string } | null = null;
  if (verified) {
    factorId = verified.id;
  } else {
    // Abandoned enrolments are removed so the account never accumulates unverified factors.
    for (const f of factors?.all ?? []) {
      if (f.factor_type === 'totp' && f.status === 'unverified') await supabase.auth.mfa.unenroll({ factorId: f.id });
    }
    const { data, error } = await supabase.auth.mfa.enroll({ factorType: 'totp' });
    if (error || !data) redirect('/mfa?e=INTERNAL');
    factorId = data.id;
    enrolment = { qr: data.totp.qr_code, secret: data.totp.secret };
  }

  return (
    <AuthCard
      title={enrolment ? t('auth.mfaEnrollTitle') : t('auth.mfaVerifyTitle')}
      lede={enrolment ? t('auth.mfaEnrollLede') : t('auth.mfaVerifyLede')}
    >
      <Flash params={params} />
      {enrolment ? (
        <div className="stack">
          <p>{t('auth.mfaScan')}</p>
          {/* QR is an SVG data URL generated by Auth; data: images are allowed by the CSP. */}
          <img className="qr" src={enrolment.qr} alt="" width={180} height={180} />
          <p className="secret">
            <span className="muted">{t('auth.mfaSecret')}: </span>
            <code>{enrolment.secret}</code>
          </p>
        </div>
      ) : null}
      <TotpForm
        factorId={factorId}
        labels={{
          code: t('auth.mfaCode'),
          confirm: t('auth.confirm'),
          errors: { MFA_INVALID: t('auth.mfaInvalid'), RATE_LIMITED: t('errors.RATE_LIMITED') },
        }}
      />
      <form action={signOut}>
        <button className="btn text" type="submit">
          {t('auth.signOut')}
        </button>
      </form>
    </AuthCard>
  );
}
