import { fontStack, motion, radius, shadow, space, type } from './scale.ts';
import { themes, type ColorRoles } from './theme.ts';

const kebab = (s: string): string => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);

function colorVars(roles: ColorRoles): string {
  return Object.entries(roles)
    .map(([k, v]) => `  --color-${kebab(k)}: ${v};`)
    .join('\n');
}

/** Generates the CSS custom properties consumed by the admin app (and the HTML design prototype). */
export function toCss(): string {
  const scale = [
    ...Object.entries(space).map(([k, v]) => `  --space-${k}: ${v}px;`),
    ...Object.entries(radius).map(([k, v]) => `  --radius-${k}: ${v}px;`),
    ...Object.entries(type).flatMap(([k, t]) => [
      `  --font-size-${kebab(k)}: ${t.size}px;`,
      `  --line-height-${kebab(k)}: ${t.lineHeight}px;`,
      `  --font-weight-${kebab(k)}: ${t.weight};`,
    ]),
    `  --font-family: ${fontStack.web};`,
    `  --font-family-mono: ${fontStack.webMono};`,
    ...Object.entries(shadow).map(
      ([k, s]) => `  --shadow-${k}: ${s.x}px ${s.y}px ${s.blur}px ${s.spread}px ${s.color};`,
    ),
    `  --motion-fast: ${motion.fast}ms;`,
    `  --motion-base: ${motion.base}ms;`,
    `  --motion-slow: ${motion.slow}ms;`,
    `  --ease-out: ${motion.easeOut};`,
  ].join('\n');
  return [
    '/* Generated by @vrticos/tokens — do not edit. */',
    `:root {\n${scale}\n${colorVars(themes.light)}\n  color-scheme: light;\n}`,
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n${colorVars(themes.dark)}\n    color-scheme: dark;\n  }\n}`,
    `:root[data-theme="dark"],\n[data-theme="dark"] {\n${colorVars(themes.dark)}\n  color-scheme: dark;\n}`,
    `[data-theme="light"] {\n${colorVars(themes.light)}\n  color-scheme: light;\n}`,
    '',
  ].join('\n');
}
