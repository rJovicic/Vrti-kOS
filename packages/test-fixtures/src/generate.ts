import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { toSeedSql } from './sql.ts';
import { buildWorld } from './world.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const world = buildWorld();
writeFileSync(join(root, 'supabase', 'seed.sql'), toSeedSql(world));

const rows = world.people.map((p) => {
  const roles = p.platformAdmin ? 'platform_admin' : p.memberships.map((m) => `${m.role}@${m.orgKey}`).join(', ');
  return `| ${p.email} | ${p.firstName} ${p.lastName} | ${roles} |`;
});
writeFileSync(
  join(root, 'docs', 'architecture', 'demo-accounts.md'),
  [
    '# Demo accounts (synthetic)',
    '',
    'Generated by `pnpm seed:generate`. All people are fictional; the `.test` domain cannot receive mail.',
    'Sign-in uses an e-mail code read from Mailpit (http://127.0.0.1:54324). Managers and the platform admin',
    'must enrol TOTP MFA on first sign-in (SR-AUTHN-07) in the admin app.',
    '',
    '| E-mail | Name | Roles |',
    '|---|---|---|',
    ...rows,
    '',
    '## Staff assignments',
    '',
    'Each `odgojitelj.<vrtić>.<n>` is the regular educator of group n. `odgojitelj.alfa.1` is also an approved',
    'substitute in Sunčice from the day the seed is loaded for five days.',
    '',
    '## Invitations (Vrtić Alfa)',
    '',
    '| E-mail | Role | State |',
    '|---|---|---|',
    ...world.invitations.map((i) => `| ${i.email} | ${i.role} | ${i.state} |`),
    '',
    '## Children',
    '',
    `${world.children.length} fictional children: five per group, enrolled since 2026-09-01, and Nika Zgrablić, linked but not enrolled in a group (D-32).`,
    '',
    '## Guardians',
    '',
    'Each `roditelj.<vrtić>.<n>` is the guardian of child n of that kindergarten. `roditelj.alfa.2` is also a second guardian',
    'of child 1 (without the right to report absences); `roditelj.alfa.1` also has the child without a group; `roditelj.oba`',
    'has one child in each kindergarten (one guardian record per kindergarten). Tea Blažević is entered without an account.',
    '',
    'Only the pending invitation can be accepted: sign in as that address after an invite was sent through the',
    'admin app (the seed does not create Auth accounts for invited people).',
    '',
  ].join('\n'),
);
console.log(`seed: ${world.orgs.length} organizations, ${world.people.length} people, ${world.assignments.length} assignments, ${world.invitations.length} invitations, ${world.children.length} children, ${world.guardians.length} guardians, ${world.guardianLinks.length} guardian links`);
