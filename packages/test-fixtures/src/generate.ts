import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { toSeedSql } from './sql.ts';
import { buildWorld } from './world.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const world = buildWorld();
writeFileSync(join(root, 'supabase', 'seed.sql'), toSeedSql(world));

const who = (id: string) => {
  const p = world.people.find((x) => x.id === id)!;
  return `${p.firstName} ${p.lastName}`;
};
const galebovi = world.children.filter((c) => c.groupId === world.scenario.groupId);
const state = (childId: string) => {
  const arrival = world.scenario.attendance.find((a) => a.childId === childId);
  if (arrival) return `arrived at ${arrival.time}${arrival.handoverLinkId ? ', handed over by the guardian' : ''}`;
  if (world.scenario.absence.childId === childId) return 'absence reported for today and tomorrow (by the guardian)';
  return 'expected (not yet arrived)';
};

const rows = world.people.map((p) => {
  const roles = p.platformAdmin ? 'platform_admin' : p.memberships.map((m) => `${m.role}@${m.orgKey}`).join(', ');
  return `| ${p.email} | ${p.firstName} ${p.lastName} | ${roles} |`;
});
writeFileSync(
  join(root, 'docs', 'architecture', 'demo-accounts.md'),
  [
    '# Demo accounts (synthetic)',
    '',
    'Generated by `pnpm seed:generate`. All people are fictional; the `.test` domain cannot receive mail.',
    'Sign-in uses an e-mail code read from Mailpit (http://127.0.0.1:54324). Managers and the platform admin',
    'must enrol TOTP MFA on first sign-in (SR-AUTHN-07) in the admin app.',
    '',
    '| E-mail | Name | Roles |',
    '|---|---|---|',
    ...rows,
    '',
    '## Staff assignments',
    '',
    'Each `odgojitelj.<vrtić>.<n>` is the regular educator of group n. `odgojitelj.alfa.1` is also an approved',
    'substitute in Sunčice from the day the seed is loaded for five days.',
    '',
    '## Invitations (Vrtić Alfa)',
    '',
    '| E-mail | Role | State |',
    '|---|---|---|',
    ...world.invitations.map((i) => `| ${i.email} | ${i.role} | ${i.state} |`),
    '',
    '## Children',
    '',
    `${world.children.length} fictional children: five per group, enrolled since 2026-09-01, and Nika Zgrablić, linked but not enrolled in a group (D-32).`,
    '',
    '## Guardians',
    '',
    'Each `roditelj.<vrtić>.<n>` is the guardian of child n of that kindergarten. `roditelj.alfa.2` is also a second guardian',
    'of child 1 (without the right to report absences); `roditelj.alfa.1` also has the child without a group; `roditelj.oba`',
    'has one child in each kindergarten (one guardian record per kindergarten). Tea Blažević is entered without an account.',
    '',
    '## Pickup authorizations (D2-D)',
    '',
    `${world.pickupAuthorizations.length} fictional persons authorized to pick up a child (name only, valid since 2026-09-01): two for child 1`,
    'of Alfa, one for child 2 of Alfa, one for child 1 of Beta. Only managers maintain the list; guardians and the',
    'educator of the group read it.',
    '',
    'Only the pending invitation can be accepted: sign in as that address after an invite was sent through the',
    'admin app (the seed does not create Auth accounts for invited people).',
    '',
    '## D5 presentation scenario (Vrtić Alfa, Galebovi — relative to the day the seed is loaded)',
    '',
    'Used by docs/product/demo-script.md. Every `pnpm demo` (database reset) restores exactly this state.',
    '',
    '| Who / what | Synthetic value |',
    '|---|---|',
    `| Manager (web) | ${who(world.scenario.managerId)} — uprava.alfa@${'demo.vrtic.test'} |`,
    `| Educator of Galebovi (mobile) | ${who(world.scenario.educatorId)} — odgojitelj.alfa.1@demo.vrtic.test |`,
    `| Guardian (mobile) | ${who(world.scenario.conversation.guardianId)} — roditelj.alfa.1@demo.vrtic.test |`,
    ...galebovi.map((c, i) => `| Child ${i + 1} of Galebovi | ${c.firstName} ${c.lastName} — ${state(c.id)} |`),
    ...world.scenario.announcements.map((a) => `| Announcement | „${a.title}” — ${a.scope === 'organization' ? 'whole kindergarten, guardians and staff' : 'Galebovi, guardians'}, published ${a.daysAgo === 0 ? 'today' : 'yesterday'} |`),
    `| Daily overviews | Galebovi, the two previous days (today's is written live in the demo) |`,
    `| Conversation | about child 1: the guardian's message and the educator's reply (yesterday), unread for the guardian |`,
    '',
  ].join('\n'),
);
console.log(`seed: ${world.orgs.length} organizations, ${world.people.length} people, ${world.assignments.length} assignments, ${world.invitations.length} invitations, ${world.children.length} children, ${world.guardians.length} guardians, ${world.guardianLinks.length} guardian links, ${world.pickupAuthorizations.length} pickup authorizations`);
